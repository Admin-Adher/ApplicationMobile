-- Safe, deliberately small runtime payload for mobile clients. No registry
-- key, tenant metadata or quarantine detail is exposed.
create or replace function public.get_client_security_requirements()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'private_media_storage', coalesce(f.enabled, false),
    'phase', coalesce(f.details ->> 'phase', 'dual_read'),
    'minimum_android_build', coalesce(
      case
        when (f.details ->> 'minimum_android_build') ~ '^[0-9]+$'
          then (f.details ->> 'minimum_android_build')::integer
        else 0
      end,
      0
    ),
    'minimum_media_protocol', coalesce(
      case
        when (f.details ->> 'minimum_media_protocol') ~ '^[0-9]+$'
          then (f.details ->> 'minimum_media_protocol')::integer
        else 1
      end,
      1
    ),
    'minimum_client_version', f.details ->> 'minimum_client_version',
    'download_url', 'https://github.com/Admin-Adher/ApplicationMobile/releases/latest/download/buildtrack-release.apk'
  )
  from (select 1) seed
  left join private.runtime_security_flags f on f.flag = 'private_media_storage'
$$;

revoke all on function public.get_client_security_requirements() from public;
grant execute on function public.get_client_security_requirements() to anon, authenticated, service_role;

-- Disable the earlier two-argument finalizer so the R2-retirement and numeric
-- build gates cannot be bypassed accidentally.
create or replace function public.server_finalize_private_media_storage(
  p_minimum_client_version text,
  p_confirm boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  raise exception 'Use the guarded four-argument private-media finalizer'
    using errcode = '0A000';
end;
$$;

create or replace function public.server_finalize_private_media_storage(
  p_minimum_client_version text,
  p_minimum_android_build integer,
  p_public_r2_retired boolean,
  p_confirm boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_version text := nullif(btrim(p_minimum_client_version), '');
  v_preflight jsonb;
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('buildtrack.private_media_cutover', 0)
  );

  if p_confirm is not true
     or v_version is null
     or coalesce(p_minimum_android_build, 0) <= 0
     or p_public_r2_retired is not true then
    raise exception 'Explicit confirmation, compatible build, and retired public R2 are required'
      using errcode = '22023';
  end if;

  v_preflight := private.media_cutover_preflight();
  if coalesce((v_preflight ->> 'ready')::boolean, false) is not true then
    raise exception 'Private-media preflight failed: %', v_preflight::text
      using errcode = '55000';
  end if;

  update storage.buckets
  set public = false
  where id in ('photos', 'documents');

  if (select count(*) from storage.buckets b where b.id in ('photos', 'documents') and not b.public) <> 2 then
    raise exception 'Both BuildTrack media buckets must exist and be private'
      using errcode = '55000';
  end if;

  insert into private.runtime_security_flags(flag, enabled, details, updated_at, updated_by)
  values (
    'private_media_storage',
    true,
    jsonb_build_object(
      'phase', 'private',
      'minimum_client_version', v_version,
      'minimum_android_build', p_minimum_android_build,
      'minimum_media_protocol', 1,
      'public_r2_retired', true,
      'activated_at', now(),
      'preflight', v_preflight
    ),
    now(),
    auth.uid()
  )
  on conflict (flag) do update
  set enabled = excluded.enabled,
      details = excluded.details,
      updated_at = excluded.updated_at,
      updated_by = excluded.updated_by;

  return jsonb_build_object(
    'enabled', true,
    'minimum_client_version', v_version,
    'minimum_android_build', p_minimum_android_build,
    'minimum_media_protocol', 1,
    'public_r2_retired', true,
    'buckets', jsonb_build_array('photos', 'documents'),
    'preflight', v_preflight
  );
end;
$$;

revoke all on function public.server_finalize_private_media_storage(text, boolean)
  from public, anon, authenticated;
revoke all on function public.server_finalize_private_media_storage(text, integer, boolean, boolean)
  from public, anon, authenticated;
grant execute on function public.server_finalize_private_media_storage(text, boolean)
  to service_role;
grant execute on function public.server_finalize_private_media_storage(text, integer, boolean, boolean)
  to service_role;

notify pgrst, 'reload schema';
