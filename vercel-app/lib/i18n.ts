export type SupportedLang = 'fr' | 'en' | 'es';

export const LANG_PARAM = 'lang';

export type Primitive = string | number | boolean | null | undefined;
export type WebTranslator = (key: string, params?: Record<string, Primitive>) => string;

export const WEB_LANGUAGES: Array<{ code: SupportedLang; label: string; nativeName: string; shortLabel: string }> = [
  { code: 'fr', label: 'Français', nativeName: 'Français', shortLabel: 'FR' },
  { code: 'en', label: 'English', nativeName: 'English', shortLabel: 'EN' },
  { code: 'es', label: 'Español', nativeName: 'Español', shortLabel: 'ES' },
];

export function normalizeLang(value?: string | null): SupportedLang {
  const raw = String(value ?? '').toLowerCase();
  if (raw.startsWith('en')) return 'en';
  if (raw.startsWith('es')) return 'es';
  return 'fr';
}

export function getBrowserLang(): SupportedLang {
  if (typeof navigator === 'undefined') return 'fr';
  return normalizeLang(navigator.languages?.[0] ?? navigator.language);
}

export function getRequestedLang(source?: URLSearchParams | ((name: string) => string | null) | null): SupportedLang {
  if (typeof source === 'function') return normalizeLang(source(LANG_PARAM) ?? getBrowserLang());
  return normalizeLang(source?.get(LANG_PARAM) ?? getBrowserLang());
}

export function appendLang(url: string, lang: SupportedLang): string {
  try {
    const target = new URL(url, 'https://buildtrack.local');
    target.searchParams.set(LANG_PARAM, lang);
    return `${target.pathname}${target.search}${target.hash}`;
  } catch {
    const separator = url.includes('?') ? '&' : '?';
    return `${url}${separator}${LANG_PARAM}=${encodeURIComponent(lang)}`;
  }
}

export function localeForLang(lang: SupportedLang): string {
  // en-GB (jour/mois) pour rester cohérent avec les PDF, emails et la page
  // publique réserve qui formatent déjà en en-GB.
  if (lang === 'en') return 'en-GB';
  if (lang === 'es') return 'es-ES';
  return 'fr-FR';
}

