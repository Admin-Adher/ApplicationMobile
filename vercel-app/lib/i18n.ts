function normalizedStaticText(value: string) {
  return value.replace(/\s+/g, ' ').trim();
}

function reverseKeyTranslation(value: string, lang: SupportedLang) {
  if (lang === 'fr') return value;
  const entry = Object.entries(WEB_TRANSLATIONS.fr).find(([, source]) => normalizedStaticText(source) === value);
  return entry ? WEB_TRANSLATIONS[lang][entry[0]] : undefined;
}

