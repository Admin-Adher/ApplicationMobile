export function translateWebStaticText(value: string, lang: SupportedLang): string {
  const trimmed = normalizedStaticText(value);
  if (!trimmed) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  if (lang === 'fr') return `${leading}${trimmed}${trailing}`;
  const translated =
    reverseKeyTranslation(trimmed, lang) ??
    WEB_STATIC_TEXT_AUDIT_PATCH[lang][trimmed] ??
    WEB_STATIC_TEXT_COMPLETION[lang][trimmed] ??
    WEB_STATIC_TEXT[lang][trimmed] ??
    translateStaticPattern(trimmed, lang) ??
    trimmed;
  return `${leading}${translated}${trailing}`;
}

function interpolate(template: string, params?: Record<string, Primitive>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name];
    return value === null || value === undefined ? '' : String(value);
  });
}

export function createWebT(lang: SupportedLang = 'fr'): WebTranslator {
  return (key, params) => {
    const template = WEB_TRANSLATIONS[lang]?.[key] ?? WEB_TRANSLATIONS.fr[key] ?? key;
    return interpolate(template, params);
  };
}
