export function reserveDuplicatePayload(source: Record<string, any>, id: string, createdAt: string, history: unknown[]) {
  return {
    id,
    kind: source.kind === 'observation' ? 'observation' : 'reserve',
    title: (String(source.title ?? '').trim() + ' (copie)').slice(0, 200),
    description: source.description ?? '',
    building: source.building ?? '',
    building_id: source.building_id ?? null,
    level: source.level ?? '',
    level_id: source.level_id ?? null,
    zone: source.zone ?? '',
    company: source.company ?? '',
    companies: Array.isArray(source.companies) ? [...source.companies] : [source.company].filter(Boolean),
    priority: source.priority ?? 'medium',
    plan_id: source.plan_id ?? null,
    plan_x: source.plan_x ?? null,
    plan_y: source.plan_y ?? null,
    lot_id: source.lot_id ?? null,
    chantier_id: source.chantier_id ?? null,
    organization_id: source.organization_id,
    status: 'open',
    deadline: null,
    created_at: createdAt,
    comments: [],
    history,
    photos: null,
    photo_uri: null,
    photo_annotations: null,
    visite_id: null,
  };
}
